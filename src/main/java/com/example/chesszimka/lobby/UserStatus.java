package com.example.chesszimka.lobby;

/** Статус подключённого пользователя в lobby. */
public enum UserStatus {
    /** Только что подключился, статус ещё не определён окончательно. */
    ONLINE,
    /** Готов принять или отправить приглашение на игру. */
    READY,
    /** Участвует в незавершённом обмене приглашением (отправил или получил). */
    INVITED,
    /** Находится в активной партии. */
    PLAYING,
    /** Отключился (сессия закрыта). */
    OFFLINE
}

